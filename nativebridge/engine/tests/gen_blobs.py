def assemble(mode, src):
    parts = src if isinstance(src, list) else [src]
    out = b""
    for part in parts:
        if isinstance(part, str) and part.strip().startswith("RAW"):
            hexs = part.strip().split()[1:]
            # halfword stream: little-endian halfwords in order
            for hw in hexs:
                v = int(hw, 16)
                out += v.to_bytes(2, "little")
            continue
        ks_mode = KS_MODE_ARM if mode == ARM else KS_MODE_THUMB
        ks = Ks(KS_ARCH_ARM, ks_mode + KS_MODE_LITTLE_ENDIAN)
        try:
            enc, _ = ks.asm(part.strip())
        except KsError as e:
            print(f"ASM FAIL: {e}\n{part}", file=sys.stderr)
            sys.exit(1)
        out += bytes(enc)
    return out

def disasm_all(mode, code):
    md_mode = CS_MODE_ARM if mode == ARM else CS_MODE_THUMB
    md = Cs(CS_ARCH_ARM, md_mode + CS_MODE_LITTLE_ENDIAN)
    return "; ".join(i.mnemonic + " " + i.op_str for i in md.disasm(code, 0))

